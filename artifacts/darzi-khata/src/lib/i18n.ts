export type DictKey = keyof typeof DICT;
export type Lang = 'en' | 'ur';

export type Vars = Record<string, string | number | undefined | null>;
/** Fill {name} placeholders. Numeric values are shown in Urdu digits for 'ur'. */
export function fill(s: string, vars: Vars | undefined, lang: Lang): string {
  if (!vars) return s;
  return s.replace(/\{(\w+)\}/g, (m, k: string) => {
    const v = vars[k];
    if (v === undefined || v === null) return '';
    return lang === 'ur' && typeof v === 'number' ? toUrduDigits(v) : String(v);
  });
}

let currentLang: Lang = 'en';
/** Set by AppPreferences so non-hook code (lib errors, static tables) follows the chosen language. */
export function setCurrentLang(l: Lang) { currentLang = l; }
export function getCurrentLang(): Lang { return currentLang; }

/** Dictionary entry for static domain tables (garments, methods, statuses). tk is the dictionary key. */
export function entry<K extends DictKey>(k: K): { tk: K; en: string; ur: string } {
  return { tk: k, en: DICT[k].en, ur: DICT[k].ur };
}
function joined(k: DictKey, vars: Vars | undefined, urduFirst: boolean) {
  const e = fill(DICT[k].en, vars, 'en'), u = fill(DICT[k].ur, vars, 'ur');
  return e === u ? e : pair(e, u, urduFirst);
}
/** Compatibility alias: errors and domain labels use only the selected language. */
export function bi(k: DictKey, vars?: Vars) { return tl(k, vars); }
/** Selected-language text for code outside the usePreferences hook. */
export function tl(k: DictKey, vars?: Vars) { return fill(DICT[k][currentLang], vars, currentLang); }

export function isDictKey(k: string): k is DictKey {
  return Object.prototype.hasOwnProperty.call(DICT, k);
}

/** Bilingual pair in the user's chosen order. */
export function pair(en: string, ur: string, urduFirst: boolean) {
  return urduFirst ? `${ur} / ${en}` : `${en} / ${ur}`;
}

export function tr(key: DictKey, urduFirst: boolean) {
  return DICT[key][urduFirst ? 'ur' : 'en'];
}

/** Single-language string (for compact chips where a pair would wrap). */
export function tr1(key: DictKey, lang: Lang) {
  return DICT[key][lang];
}

const moneyFmt = new Intl.NumberFormat('en-PK', { maximumFractionDigits: 0 });
/** "Rs 12,500" */
export function money(n: number) {
  const v = Math.round(Number.isFinite(n) ? n : 0);
  return `${v < 0 ? '-' : ''}Rs ${moneyFmt.format(Math.abs(v))}`;
}

const UR_MONTHS = ['جنوری', 'فروری', 'مارچ', 'اپریل', 'مئی', 'جون', 'جولائی', 'اگست', 'ستمبر', 'اکتوبر', 'نومبر', 'دسمبر'];
const UR_DIGITS = '۰۱۲۳۴۵۶۷۸۹';
export const toUrduDigits = (s: string | number) => String(s).replace(/[0-9]/g, (d) => UR_DIGITS[+d]);
/** Translate known built-in fabric values, including old bilingual demo records.
 * Custom descriptions are never changed in storage or machine-translated. */
export function fabricName(value: string, lang: Lang = getCurrentLang()): string {
  const aliases: [DictKey, string[]][] = [
    ['fabric_cotton', ['Cotton / کاٹن']],
    ['fabric_wash_wear', []],
    ['fabric_boski', ['Boski / بوسکی']],
    ['fabric_khaddar', ['Khaddar / کھدر']],
  ];
  const key = aliases.find(([key, old]) => [...old, DICT[key].en, DICT[key].ur].includes(value))?.[0];
  return key ? DICT[key][lang] : value;
}

/** Only use for identified synthetic demo records, never general user notes. */
export function demoText(value: string, lang: Lang = getCurrentLang()): string {
  for (const key of ['demo_instruction', 'demo_completed', 'demo_working', 'demo_order_note'] as const) {
    const pair = DICT[key];
    if ([pair.en, pair.ur, `${pair.en} / ${pair.ur}`].includes(value)) return pair[lang];
  }
  return value;
}
const EN_MONTHS = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];

/** "6 Nov" or "۶ نومبر" */
export function shortDate(d: Date | string, lang: Lang) {
  const x = new Date(d);
  if (Number.isNaN(x.getTime())) return '';
  return lang === 'ur' ? `${toUrduDigits(x.getDate())} ${UR_MONTHS[x.getMonth()]}` : `${x.getDate()} ${EN_MONTHS[x.getMonth()]}`;
}

/** Whole local-calendar days from `now` to `target` (negative = past). DST/timezone safe. */
export function dayDiff(target: Date | string, now: Date = new Date()) {
  const t = new Date(target), n = new Date(now);
  const a = Date.UTC(t.getFullYear(), t.getMonth(), t.getDate());
  const b = Date.UTC(n.getFullYear(), n.getMonth(), n.getDate());
  return Math.round((a - b) / 86400000);
}

/** Single-language delivery wording. tk + vars feed label(). */
export function deliveryWords(target: Date | string, now: Date = new Date()) {
  const n = dayDiff(target, now);
  const tk: DictKey = n === 0 ? 'when_today' : n === 1 ? 'when_tomorrow' : n < 0 ? 'when_late' : 'when_in_days';
  const vars = { days: Math.abs(n) };
  return { n, late: n < 0, tk, vars, en: fill(DICT[tk].en, vars, 'en'), ur: fill(DICT[tk].ur, vars, 'ur') };
}
